package io.github.eschizoid.telescope.demo.order;

import jakarta.persistence.CascadeType;
import jakarta.persistence.CollectionTable;
import jakarta.persistence.Column;
import jakarta.persistence.Convert;
import jakarta.persistence.ElementCollection;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.OneToMany;
import jakarta.persistence.OrderBy;
import jakarta.persistence.Table;
import java.time.LocalDate;
import java.util.ArrayList;
import java.util.List;

/**
 * An order, as the database stores it. It holds more than any client may see: the cost price on
 * each line, the payment provider's card token and notes the warehouse writes for itself.
 *
 * <p>{@code OrderMappings} is generated by {@code telescope-codegen} from the {@code @Bridge}
 * fields in {@link OrderMappers} whose source is an order, so an order converts itself: {@code
 * order.toOrderDto()}.
 *
 * <p>The lines have no setter. {@link #addLine(OrderLine)} is the only way in, because it is what
 * points each line back at its order.
 */
@Entity
@Table(name = "orders")
public class Order implements OrderMappings {

  @Id
  @GeneratedValue(strategy = GenerationType.IDENTITY)
  private Long id;

  @Column(unique = true)
  private String number;

  // Loaded only when something reads it, as most real associations are: until then Hibernate
  // hands out a proxy subclass of Customer.
  @ManyToOne(optional = false, fetch = FetchType.LAZY)
  @JoinColumn(name = "customer_id")
  private Customer customer;

  @Enumerated(EnumType.STRING)
  private OrderStatus status;

  @Enumerated(EnumType.STRING)
  private Delivery delivery;

  private boolean giftWrap;

  private LocalDate placedOn;

  private String discountCode;

  private String trackingNumber;

  private String internalNotes;

  @Convert(converter = PaymentColumn.class)
  private Payment payment;

  @ElementCollection
  @CollectionTable(name = "order_tags", joinColumns = @JoinColumn(name = "order_id"))
  @Column(name = "tag")
  private List<String> tags = new ArrayList<>();

  @OneToMany(mappedBy = "order", cascade = CascadeType.ALL, orphanRemoval = true)
  @OrderBy("id")
  private final List<OrderLine> lines = new ArrayList<>();

  public Order() {}

  /** Adds a line and points it back at this order. */
  public void addLine(final OrderLine line) {
    line.setOrder(this);
    lines.add(line);
  }

  /** Adds a tag, once: a tag the order already has is not added again. */
  public void addTag(final String tag) {
    if (!tags.contains(tag)) tags.add(tag);
  }

  public Long getId() {
    return id;
  }

  public void setId(final Long id) {
    this.id = id;
  }

  public String getNumber() {
    return number;
  }

  public void setNumber(final String number) {
    this.number = number;
  }

  public Customer getCustomer() {
    return customer;
  }

  public void setCustomer(final Customer customer) {
    this.customer = customer;
  }

  public OrderStatus getStatus() {
    return status;
  }

  public void setStatus(final OrderStatus status) {
    this.status = status;
  }

  public Delivery getDelivery() {
    return delivery;
  }

  public void setDelivery(final Delivery delivery) {
    this.delivery = delivery;
  }

  public boolean isGiftWrap() {
    return giftWrap;
  }

  public void setGiftWrap(final boolean giftWrap) {
    this.giftWrap = giftWrap;
  }

  public LocalDate getPlacedOn() {
    return placedOn;
  }

  public void setPlacedOn(final LocalDate placedOn) {
    this.placedOn = placedOn;
  }

  public String getDiscountCode() {
    return discountCode;
  }

  public void setDiscountCode(final String discountCode) {
    this.discountCode = discountCode;
  }

  public String getTrackingNumber() {
    return trackingNumber;
  }

  public void setTrackingNumber(final String trackingNumber) {
    this.trackingNumber = trackingNumber;
  }

  public String getInternalNotes() {
    return internalNotes;
  }

  public void setInternalNotes(final String internalNotes) {
    this.internalNotes = internalNotes;
  }

  public Payment getPayment() {
    return payment;
  }

  public void setPayment(final Payment payment) {
    this.payment = payment;
  }

  public List<String> getTags() {
    return tags;
  }

  public void setTags(final List<String> tags) {
    this.tags = tags;
  }

  public List<OrderLine> getLines() {
    return lines;
  }
}
