/**
 * The shallow copy a conversion makes of a container whose declared type is the same on both sides.
 * {@code Telescope.mapper(...)} makes it for such a component, and a bridge generated by
 * {@code @Bridge} calls it, so the two paths copy the same way.
 *
 * <p>The copy behaves like the source and never instantiates a class telescope does not know: a JDK
 * collection is copied into its own class, anything else into the nearest JDK class that keeps its
 * ordering, and failing that into the declared type's default. Unmodifiable inputs are returned as
 * they are. The elements, and a map's keys and values, are the source's own.
 *
 * <p>It is also how {@code into} writes a container property into a target that already holds one:
 * a held container that can be changed is cleared and refilled with the converted elements, so it
 * keeps its identity, and one that cannot be changed is replaced through the setter. Under the
 * {@code ADDERS} write strategy each element goes through the target's adder instead, and the value
 * {@code into} reads from is built with no adder run on it. {@code patch} refills a container the
 * bean it rebuilds from holds the same way, through a {@link Patch}. Both paths call the same
 * methods here for it.
 *
 * <p>Both decisions go through one {@link Policy}. The standard policy is the behavior described
 * above. A module that knows more about a container, such as whether a persistence provider has
 * loaded it, replaces the policy as a whole by registering one implementation of {@link Policy}
 * through {@link ServiceLoader}; every mapper and every generated bridge then takes it.
 *
 * <p>Public so generated code in any package can call it; not meant to be called directly.
 */
public final class ContainerCopy {

  private ContainerCopy() {}

  /**
   * How containers are copied and refilled. Every method has the standard behavior as its default,
   * so an implementation overrides only what it changes and can hand any case back to the standard
   * behavior: {@link ContainerCopy#standardCopy} for a copy, {@link Refill#standard} for a refill.
   *
   * <p>An implementation is registered through {@link ServiceLoader}: a {@code provides} clause in
   * a module, or a {@code META-INF/services} entry on the class path. At most one active policy may
   * be registered; it needs a public no-argument constructor, and is loaded once, the first time a
   * container is copied or refilled.
   */
  public interface Policy {
    /**
     * The copy of {@code source}, a container whose declared type is {@code declared} on both sides
     * of a conversion, or {@code source} itself to share it.
     *
     * @param source the container to copy, never null
     * @param declared the type the container is declared as on both sides
     * @return the container the converted value holds
     */
    default Object copy(final Object source, final Class<?> declared) {
      return standardCopy(source, declared);
    }

    /**
     * Writes {@link Refill#incoming()} into the container a target already holds, or through the
     * target's adder. The standard behavior is {@link Refill#standard}.
     *
     * @param refill the write, with the target, its property and both containers
     */
    default void refill(final Refill refill) {
      refill.standard();
    }

    /**
     * Whether this policy applies in this runtime, such as whether the persistence API it consults
     * is on the class path. A policy that answers false is passed over as if it were not
     * registered, so a module carrying one costs nothing where what it knows about is absent.
     *
     * @return whether this policy replaces the standard one
     */
    default boolean active() {
      return true;
    }
  }

  /**
   * One container property {@code into} writes into an existing target, or the adders strategy
   * fills: the target that holds it, its name, the container the target holds and the converted
   * container whose elements it is to hold.
   */
  public static final class Refill {

    private final Object owner;
    private final String property;
    private final Object held;
    private final Object incoming;
    private final BiConsumer<Object, Object> adder;

    private Refill(
      final Object owner,
      final String property,
      final Object held,
      final Object incoming,
      final BiConsumer<Object, Object> adder
    ) {
      this.owner = owner;
      this.property = property;
      this.held = held;
      this.incoming = incoming;
      this.adder = adder;
    }

    /** The object whose property is written. */
    public Object owner() {
      return owner;
    }

    /** The name of the property written. */
    public String property() {
      return property;
    }

    /**
     * The {@code Collection} or {@code Map} the owner holds for the property. Null only where an
     * adder fills the property and the owner holds no collection.
     */
    public Object held() {
      return held;
    }

    /**
     * The {@code Collection} or {@code Map} converted from the source, whose elements the property
     * is to hold. Never the container {@link #held()} returns. Null only where an adder fills the
     * property and the source holds no collection, which leaves it empty.
     */
    public Object incoming() {
      return incoming;
    }

    /** Whether each element is added through the owner's adder rather than to {@link #held()}. */
    public boolean throughAdder() {
      return adder != null;
    }

    /** Adds one element as this write adds it: through the owner's adder, or to {@link #held()}. */
    @SuppressWarnings("unchecked")
    public void add(final Object element) {
      if (adder != null) {
        adder.accept(owner, element);
      } else {
        ((Collection<Object>) held).add(element);
      }
    }

    /**
     * The standard refill: clears {@link #held()}, then adds every element of {@link #incoming()},
     * through the adder where there is one, and puts every entry where the property is a map.
     */
    public void standard() {
      standardRefill(owner, held, incoming, adder);
    }
  }

  /** The policy that is the standard behavior, and the one taken when none is registered. */
  private static final Policy STANDARD = new Policy() {};

  /** The policy every copy and refill goes through. */
  private static final Policy POLICY = registeredPolicy();

  private static Policy registeredPolicy() {
    final var registered = new ArrayList<Policy>();
    for (final var policy : ServiceLoader.load(Policy.class, ContainerCopy.class.getClassLoader())) {
      if (policy.active()) {
        registered.add(policy);
      }
    }
    if (registered.size() > 1) throw new IllegalStateException(
      "ContainerCopy: more than one active ContainerCopy.Policy is registered (" +
        registered
          .stream()
          .map(policy -> policy.getClass().getName())
          .toList() +
        "); register at most one that is active."
    );
    return registered.isEmpty() ? STANDARD : registered.getFirst();
  }

  /**
   * A shallow copy of {@code source}, or {@code source} itself when it is null or unmodifiable, as
   * the registered {@link Policy} decides.
   *
   * @param source the container to copy
   * @param declared the type the container is declared as on both sides
   * @param <C> the container's type
   * @return the copy
   */
  @SuppressWarnings("unchecked")
  public static <C> C of(final C source, final Class<?> declared) {
    if (source == null) return null;
    return POLICY == STANDARD ? standardCopy(source, declared) : (C) POLICY.copy(source, declared);
  }

  /**
   * Refuses, by name, a container property {@code into} cannot write at all, as {@link
   * CollectionWrites#intoWrite} decides it from what is known before anything is written: the
   * target holds no container, or an unmodifiable JDK one, and has no setter, and no adder fills
   * it. Called for every container property before {@code into} writes anything, so a call refused
   * here leaves the target as it was.
   *
   * @param held the container the target holds for {@code property}, or null
   * @param incoming the container converted from the source, or null
   * @param setter whether the target class has a setter for {@code property}
   * @param adder whether an adder fills {@code property}
   * @param source the simple name of the mapper's source class
   * @param target the simple name of the mapper's target class
   * @param bean the simple name of the target's class
   * @param property the name of the property
   * @throws IllegalArgumentException if nothing can write {@code property}
   */
  public static void refuseUnwritable(
    final Object held,
    final Object incoming,
    final boolean setter,
    final boolean adder,
    final String source,
    final String target,
    final String bean,
    final String property
  ) {
    final var write = CollectionWrites.intoWrite(held != null, changeable(held), incoming != null, setter, adder);
    if (write == CollectionWrites.IntoWrite.REFUSE) throw unwritable(source, target, bean, property, held, null);
  }

  /**
   * Writes {@code incoming}, the container converted from the source, into {@code held}, the {@code
   * Collection} or {@code Map} {@code owner} holds for {@code property}, where {@link
   * CollectionWrites#intoWrite} refills it: cleared and then given every element or entry of {@code
   * incoming}, as the registered {@link Policy} decides, so it keeps its identity. Answers false
   * where the caller is to write {@code incoming} through the setter instead: the target holds no
   * container, holds one that cannot be changed, or {@code incoming} is null. A held container
   * whose refill throws, as one that cannot change throws {@link UnsupportedOperationException} and
   * a sorted set handed a null throws {@link NullPointerException}, has its elements put back and
   * is treated as one that cannot be changed.
   *
   * @param source the simple name of the mapper's source class
   * @param target the simple name of the mapper's target class
   * @param owner the target whose property is written
   * @param property the name of the property
   * @param held the container {@code owner} holds, or null
   * @param incoming the container converted from the source, or null
   * @param setter whether the target class has a setter for {@code property}
   * @return whether the property is written; false where the caller writes it through the setter
   * @throws IllegalArgumentException if the property has no setter and the held container cannot be
   *     changed
   */
  public static boolean refill(
    final String source,
    final String target,
    final Object owner,
    final String property,
    final Object held,
    final Object incoming,
    final boolean setter
  ) {
    return write(source, target, owner, property, held, incoming, null, setter);
  }

  /**
   * A new record of the containers one {@code patch} call refills, for the call to {@link
   * Patch#undo} should the rebuild fail.
   *
   * @return an empty patch
   */
  public static Patch patching() {
    return new Patch();
  }

  /**
   * The containers one {@code patch} call refills in the bean it rebuilds from, so that a rebuild
   * that fails leaves that bean as it was. Both paths refill every container before the rebuild,
   * and undo every refill when the rebuild throws.
   */
  public static final class Patch {

    private final List<Object> held = new ArrayList<>(2);
    private final List<Object> kept = new ArrayList<>(2);

    private Patch() {}

    /**
     * The container {@code patch} gives {@code property} of the bean it rebuilds from {@code
     * owner}, where the partial supplies {@code incoming} for it and {@code owner} holds {@code
     * held}: {@code held} itself, cleared and refilled with the elements or entries of {@code
     * incoming} as the registered {@link Policy} decides, so the rebuilt bean keeps the instance
     * {@code owner} holds, which a provider tracking a managed collection by instance needs. {@code
     * incoming} where {@code held} is null, is {@code incoming} itself or cannot be changed: an
     * unmodifiable JDK container is known in advance, and one that cannot even be read, or whose
     * refill throws, has its elements put back and is passed over the same way.
     *
     * @param owner the bean {@code patch} rebuilds
     * @param property the name of the property
     * @param held the {@code Collection} or {@code Map} {@code owner} holds for {@code property},
     *     or null
     * @param incoming the container converted from the partial, or null
     * @param <C> the property's declared type
     * @return the container the rebuilt bean holds for {@code property}
     */
    public <C> C refill(final Object owner, final String property, final C held, final C incoming) {
      if (held == null || incoming == null || held == incoming || !changeable(held)) {
        return incoming;
      }
      if (!(held instanceof Collection<?> || held instanceof Map<?, ?>)) {
        return incoming;
      }
      final Object before;
      try {
        before = snapshot(held);
      } catch (final RuntimeException unreadable) {
        return incoming;
      }
      // With a setter to fall back on, a refill that fails answers false rather than refusing, so
      // the class names a refusal would carry are never read.
      if (!refillHeld(null, null, owner, property, held, incoming, null, true)) {
        return incoming;
      }
      this.held.add(held);
      this.kept.add(before);
      return held;
    }

    /**
     * Puts back what every container {@link #refill} refilled held before, last refilled first,
     * for a {@code patch} whose rebuild failed. What a container that will not take its elements
     * back throws is added to {@code failure}.
     *
     * @param failure what the rebuild threw
     */
    public void undo(final RuntimeException failure) {
      for (var i = held.size() - 1; i >= 0; i--) {
        restore(held.get(i), kept.get(i), failure);
      }
    }
  }

  /**
   * Fills collection {@code property} of {@code owner} through its {@code adder}, where {@link
   * CollectionWrites#intoWrite} refills it: {@code held}, the collection {@code owner} holds, is
   * cleared when there is one, and then each element of {@code incoming} is passed to the adder, as
   * the registered {@link Policy} decides. A null {@code incoming} adds nothing. Answers false
   * where the held collection itself cannot be changed and the caller is to write {@code incoming}
   * through the setter instead. An exception the adder throws, rejecting an element, is thrown on
   * as it is once the held collection has its elements back, setter or not.
   *
   * @param source the simple name of the mapper's source class
   * @param target the simple name of the mapper's target class
   * @param owner the target whose property is written
   * @param property the name of the property
   * @param held the collection {@code owner} holds, or null
   * @param incoming the collection converted from the source, or null
   * @param adder the target's adder for the property
   * @param setter whether the target class has a setter for {@code property}
   * @param <O> the target's type
   * @param <E> the element type
   * @return whether the property is written; false where the caller writes it through the setter
   * @throws IllegalArgumentException if the property has no setter and the held collection cannot
   *     be changed
   */
  @SuppressWarnings("unchecked")
  public static <O, E> boolean fill(
    final String source,
    final String target,
    final O owner,
    final String property,
    final Object held,
    final Collection<? extends E> incoming,
    final BiConsumer<? super O, ? super E> adder,
    final boolean setter
  ) {
    return write(source, target, owner, property, held, incoming, (BiConsumer<Object, Object>) adder, setter);
  }

  private static boolean write(
    final String source,
    final String target,
    final Object owner,
    final String property,
    final Object held,
    final Object incoming,
    final BiConsumer<Object, Object> adder,
    final boolean setter
  ) {
    return switch (
      CollectionWrites.intoWrite(held != null, changeable(held), incoming != null, setter, adder != null)
    ) {
      case SET -> false;
      case REFUSE -> throw unwritable(source, target, beanOf(owner), property, held, null);
      case REFILL -> refillHeld(source, target, owner, property, held, incoming, adder, setter);
    };
  }

  /**
   * Refills {@code held} with {@code incoming} through the registered {@link Policy}. A refill that
   * fails first has the elements {@code held} had put back, so whoever else holds it sees it as it
   * was wherever it takes its elements back; then {@link CollectionWrites#afterFailedRefill}
   * decides. An exception the adder throws is the adder rejecting an element and goes to the caller
   * as it was thrown, never past the adder to the setter. One the container throws, such as {@code
   * UnsupportedOperationException} from a container that cannot change or {@code
   * NullPointerException} from a sorted set handed a null, answers false where a setter can write
   * the property instead, and refuses the call by name, with the failure as its cause, where none
   * can.
   */
  private static boolean refillHeld(
    final String source,
    final String target,
    final Object owner,
    final String property,
    final Object held,
    final Object incoming,
    final BiConsumer<Object, Object> adder,
    final boolean setter
  ) {
    if (held == incoming && adder == null) return true;
    // A held container that cannot even be read, such as a provider's lazy collection outside its
    // session, fails in the snapshot before anything is changed, and is treated as one that cannot
    // change.
    Object kept = null;
    Object elements = null;
    // What the adder throws is told apart from what the container throws.
    final BiConsumer<Object, Object> adds =
      adder == null
        ? null
        : (bean, element) -> {
            try {
              adder.accept(bean, element);
            } catch (final RuntimeException rejected) {
              throw new AdderRejected(rejected);
            }
          };
    try {
      kept = snapshot(held);
      // The elements are taken before the held container is cleared, so an incoming container that
      // reads through to the held one, such as the held list itself or an unmodifiable view of it,
      // still fills it.
      elements = detached(held, incoming);
      if (POLICY == STANDARD) {
        standardRefill(owner, held, elements, adds);
      } else {
        POLICY.refill(new Refill(owner, property, held, elements, adds));
      }
    } catch (final RuntimeException failed) {
      final var adderThrew = failed instanceof AdderRejected;
      final var cause = adderThrew ? (RuntimeException) failed.getCause() : failed;
      restore(held, kept, cause);
      return switch (CollectionWrites.afterFailedRefill(adderThrew, setter)) {
        case SET -> false;
        case REFUSE -> throw unwritable(source, target, beanOf(owner), property, held, cause);
        case RETHROW -> throw cause;
      };
    }
    return true;
  }

  /** Carries what an adder threw out of a refill, so it is not taken for the container's own. */
  private static final class AdderRejected extends RuntimeException {

    private static final long serialVersionUID = 1L;

    AdderRejected(final RuntimeException rejected) {
      super(null, rejected, false, false);
    }
  }

  /**
   * {@code incoming} where it is a container with storage of its own, one of the JDK classes a copy
   * constructor builds that is not {@code held} itself; otherwise a copy of its elements or entries.
   * Anything else may read through to {@code held}: the held container itself, an unmodifiable or
   * synchronized view of it, a sub-list of it, or a container a library wraps around it, and clearing
   * {@code held} would empty it before its elements were read.
   */
  @SuppressWarnings({ "unchecked", "rawtypes" })
  private static Object detached(final Object held, final Object incoming) {
    if (incoming == null || (incoming != held && COPY_CONSTRUCTORS.containsKey(incoming.getClass()))) {
      return incoming;
    }
    return incoming instanceof Map map ? new LinkedHashMap<>(map) : new ArrayList<>((Collection) incoming);
  }

  /** A copy of what {@code held} holds, to put back if a refill fails; null for no container. */
  @SuppressWarnings({ "unchecked", "rawtypes" })
  private static Object snapshot(final Object held) {
    return switch (held) {
      case null -> null;
      case Map map -> new LinkedHashMap<>(map);
      default -> new ArrayList<>((Collection) held);
    };
  }

  /**
   * Puts {@code kept} back into {@code held}, as {@link #snapshot} took it. A container that will
   * not take its elements back keeps what it holds, and what it threw is added to {@code failure}.
   */
  @SuppressWarnings({ "unchecked", "rawtypes" })
  private static void restore(final Object held, final Object kept, final RuntimeException failure) {
    if (kept == null) return;
    try {
      if (held instanceof Map map) {
        map.clear();
        map.putAll((Map) kept);
      } else {
        ((Collection) held).clear();
        ((Collection) held).addAll((Collection) kept);
      }
    } catch (final RuntimeException notRestored) {
      failure.addSuppressed(notRestored);
    }
  }

  /** The target's class as a message names it. */
  private static String beanOf(final Object owner) {
    return PairingMessages.className(owner.getClass());
  }

  /** Whether {@code held} is a container that is not known to be unchangeable. */
  private static boolean changeable(final Object held) {
    return held != null && !UNMODIFIABLE.contains(held.getClass());
  }

  private static IllegalArgumentException unwritable(
    final String source,
    final String target,
    final String bean,
    final String property,
    final Object held,
    final RuntimeException cause
  ) {
    return new IllegalArgumentException(
      PairingMessages.intoUnwritable(source, target, bean, property, held == null ? null : held.getClass().getName()),
      cause
    );
  }

  /**
   * Passes each of {@code elements} to {@code adder} on {@code owner}, which the adders strategy
   * does for each collection property of a bean it builds. While {@link #deferAdders} builds a
   * value of {@code owner}'s class, the elements are recorded instead. A null {@code elements} adds
   * nothing.
   *
   * @param owner the bean being built
   * @param property the name of the property
   * @param elements the converted collection, or null
   * @param adder the bean's adder for the property
   * @param <O> the bean's type
   * @param <E> the element type
   */
  @SuppressWarnings("unchecked")
  public static <O, E> void add(
    final O owner,
    final String property,
    final Iterable<? extends E> elements,
    final BiConsumer<? super O, ? super E> adder
  ) {
    AdderCalls.add(owner, property, elements, (BiConsumer<Object, Object>) adder);
  }

  /**
   * Builds a value of exactly {@code owner} through {@code build} with none of that class's adders
   * called on it, which is how {@code into} converts a source whose target is filled through its
   * adders: the value comes back with the collections its adders were to be handed, for the
   * target's own adders to take. Any other instance of {@code owner} built on the way has its
   * adders called before this returns.
   *
   * @param owner the class the adders strategy builds
   * @param build the conversion, {@code forward(source)}
   * @param <T> the class built
   * @return the value built and the collections its adders were to be handed
   */
  public static <T> Deferred<T> deferAdders(final Class<T> owner, final Supplier<? extends T> build) {
    final var deferred = AdderCalls.deferring(owner, build::get);
    return new Deferred<>(deferred.value(), deferred.elements());
  }

  /**
   * A value {@link #deferAdders} built, and by property the collection each of its adders was to be
   * handed.
   *
   * @param <T> the class built
   */
  public static final class Deferred<T> {

    private final T value;
    private final Map<String, Object> elements;

    private Deferred(final T value, final Map<String, Object> elements) {
      this.value = value;
      this.elements = elements;
    }

    /** The value built. */
    public T value() {
      return value;
    }

    /**
     * The collection the adder of {@code property} was to be handed, or null where the converted
     * value was null.
     *
     * @param property the name of the property
     * @param <C> the property's declared type
     * @return the converted collection, or null
     */
    @SuppressWarnings("unchecked")
    public <C> C elements(final String property) {
      return (C) elements.get(property);
    }
  }

  @SuppressWarnings({ "unchecked", "rawtypes" })
  private static void standardRefill(
    final Object owner,
    final Object held,
    final Object incoming,
    final BiConsumer<Object, Object> adder
  ) {
    if (held instanceof Map map) {
      map.clear();
      if (incoming != null) map.putAll((Map) incoming);
      return;
    }
    if (held != null) ((Collection) held).clear();
    if (incoming == null) return;
    if (adder == null) {
      ((Collection) held).addAll((Collection) incoming);
    } else {
      for (final var element : (Collection<?>) incoming) adder.accept(owner, element);
    }
  }

  /**
   * The standard copy: a shallow copy of {@code source} into its own class where it is a JDK
   * container, else into the nearest JDK class that keeps its ordering, else into the declared
   * type's default; {@code source} itself when it is unmodifiable. For a {@link Policy} to hand a
   * container back to.
   *
   * @param source the container to copy, not null
   * @param declared the type the container is declared as on both sides
   * @param <C> the container's type
   * @return the copy
   */
  @SuppressWarnings({ "unchecked", "rawtypes" })
  public static <C> C standardCopy(final C source, final Class<?> declared) {
    if (UNMODIFIABLE.contains(source.getClass())) return source;
    final var own = OWN_CLASS_COPIES.get(source.getClass());
    if (own != NO_COPY) return (C) own.apply(source);
    // An ordering the class cannot be rebuilt with is kept by the JDK class that carries one, where
    // the declared type can hold it.
    if (source instanceof SortedSet sorted && declared.isAssignableFrom(TreeSet.class)) {
      return (C) new TreeSet<>(sorted);
    }
    if (source instanceof SortedMap sorted && declared.isAssignableFrom(TreeMap.class)) {
      return (C) new TreeMap<>(sorted);
    }
    if (source instanceof PriorityQueue queue && declared.isAssignableFrom(PriorityQueue.class)) {
      return (C) new PriorityQueue<>(queue);
    }
    return (C) DECLARED_COPIES.get(declared).apply(source);
  }

  /** Marks a runtime class with no copy into itself. */
  private static final Function<Object, Object> NO_COPY = input -> {
    throw new IllegalStateException("no copy for " + input.getClass().getName());
  };

  /**
   * The JDK containers whose copy constructor builds an equal container of the same class, keeping
   * the comparator of a sorted one. They are named rather than probed, so no constructor is looked
   * up at run time, and a copy constructor takes the source's elements in one step. Every class the
   * shared allocation table rebuilds a declared type as is among them, which is what the fallback
   * for a declared type relies on.
   */
  @SuppressWarnings({ "unchecked", "rawtypes" })
  private static final Map<Class<?>, Function<Object, Object>> COPY_CONSTRUCTORS = Map.ofEntries(
    Map.entry(ArrayList.class, input -> new ArrayList<>((Collection) input)),
    Map.entry(LinkedList.class, input -> new LinkedList<>((Collection) input)),
    Map.entry(ArrayDeque.class, input -> new ArrayDeque<>((Collection) input)),
    Map.entry(Vector.class, input -> new Vector<>((Collection) input)),
    Map.entry(Stack.class, input -> {
      final var stack = new Stack<>();
      stack.addAll((Collection) input);
      return stack;
    }),
    Map.entry(CopyOnWriteArrayList.class, input -> new CopyOnWriteArrayList<>((Collection) input)),
    Map.entry(CopyOnWriteArraySet.class, input -> new CopyOnWriteArraySet<>((Collection) input)),
    Map.entry(PriorityQueue.class, input -> new PriorityQueue<>((PriorityQueue) input)),
    Map.entry(PriorityBlockingQueue.class, input -> new PriorityBlockingQueue<>((PriorityBlockingQueue) input)),
    Map.entry(HashSet.class, input -> new HashSet<>((Collection) input)),
    Map.entry(LinkedHashSet.class, input -> new LinkedHashSet<>((Collection) input)),
    Map.entry(TreeSet.class, input -> new TreeSet<>((SortedSet) input)),
    Map.entry(ConcurrentSkipListSet.class, input -> new ConcurrentSkipListSet<>((SortedSet) input)),
    Map.entry(HashMap.class, input -> new HashMap<>((Map) input)),
    Map.entry(LinkedHashMap.class, input -> new LinkedHashMap<>((Map) input)),
    Map.entry(TreeMap.class, input -> new TreeMap<>((SortedMap) input)),
    Map.entry(ConcurrentSkipListMap.class, input -> new ConcurrentSkipListMap<>((SortedMap) input)),
    Map.entry(ConcurrentHashMap.class, input -> new ConcurrentHashMap<>((Map) input)),
    Map.entry(IdentityHashMap.class, input -> new IdentityHashMap<>((Map) input)),
    Map.entry(WeakHashMap.class, input -> new WeakHashMap<>((Map) input)),
    Map.entry(EnumMap.class, input -> new EnumMap<>((EnumMap) input))
  );

  /** How a container of each runtime class is copied into its own class, or {@link #NO_COPY}. */
  private static final ClassValue<Function<Object, Object>> OWN_CLASS_COPIES = new ClassValue<>() {
    @Override
    @SuppressWarnings({ "unchecked", "rawtypes" })
    protected Function<Object, Object> computeValue(final Class<?> type) {
      final var named = COPY_CONSTRUCTORS.get(type);
      if (named != null) return named;
      // EnumSet's implementations are private to java.util; clone is how the JDK copies one.
      if (EnumSet.class.isAssignableFrom(type)) return input -> ((EnumSet) input).clone();
      return NO_COPY;
    }
  };

  /**
   * The shared allocation rules, over reflection handles, which say what a declared type is rebuilt
   * as: the class the table names, or the family default standing in for an interface or abstract
   * type it does not.
   */
  private static final ContainerAllocation<Type> ALLOCATION = new ContainerAllocation<>(new ReflectionProps());

  /**
   * How a container is copied into the class the shared allocation rules rebuild a declared type
   * as.
   */
  private static final ClassValue<Function<Object, Object>> DECLARED_COPIES = new ClassValue<>() {
    @Override
    protected Function<Object, Object> computeValue(final Class<?> declared) {
      final var kind = ALLOCATION.familyOf(declared);
      if (ALLOCATION.implementationFor(declared, kind) instanceof Allocation.Build build) {
        for (final var entry : COPY_CONSTRUCTORS.entrySet()) {
          if (entry.getKey().getName().equals(build.implName())) return entry.getValue();
        }
      }
      throw new IllegalStateException("telescope rebuilds no copy of " + declared.getName());
    }
  };

  /**
   * The classes of the JDK's unmodifiable containers, read off instances of each: the {@code
   * List.of}, {@code Set.of} and {@code Map.of} families, and the {@code Collections} singletons,
   * empties and unmodifiable views. They are private classes, so an instance is the only way to
   * name one.
   */
  private static final Set<Class<?>> UNMODIFIABLE = Set.copyOf(
    List.of(
      List.of().getClass(),
      List.of(1).getClass(),
      List.of(1, 2, 3).getClass(),
      List.of(1, 2, 3).subList(0, 1).getClass(),
      Set.of().getClass(),
      Set.of(1).getClass(),
      Set.of(1, 2, 3).getClass(),
      Map.of().getClass(),
      Map.of(1, 1).getClass(),
      Map.of(1, 1, 2, 2).getClass(),
      Collections.emptyList().getClass(),
      Collections.emptySet().getClass(),
      Collections.emptySortedSet().getClass(),
      Collections.emptyNavigableSet().getClass(),
      Collections.emptyMap().getClass(),
      Collections.emptySortedMap().getClass(),
      Collections.emptyNavigableMap().getClass(),
      Collections.singletonList(1).getClass(),
      Collections.singleton(1).getClass(),
      Collections.singletonMap(1, 1).getClass(),
      Collections.unmodifiableCollection(new ArrayList<>()).getClass(),
      Collections.unmodifiableSequencedCollection(new ArrayList<>()).getClass(),
      Collections.unmodifiableList(new ArrayList<>()).getClass(),
      Collections.unmodifiableList(new LinkedList<>()).getClass(),
      Collections.unmodifiableSet(new HashSet<>()).getClass(),
      Collections.unmodifiableSequencedSet(new LinkedHashSet<>()).getClass(),
      Collections.unmodifiableSortedSet(new TreeSet<>()).getClass(),
      Collections.unmodifiableNavigableSet(new TreeSet<>()).getClass(),
      Collections.unmodifiableMap(new HashMap<>()).getClass(),
      Collections.unmodifiableSequencedMap(new LinkedHashMap<>()).getClass(),
      Collections.unmodifiableSortedMap(new TreeMap<>()).getClass(),
      Collections.unmodifiableNavigableMap(new TreeMap<>()).getClass()
    )
  );
}
